  describe('4. Scanner Security and Resource Limits', () => {
    test('assertSafePath rejects path traversal attempts with ScannerSecurityError', () => {
      const repoRoot = path.resolve('/var/app/repo');
      expect(() => assertSafePath(repoRoot, '../outside')).toThrow(ScannerSecurityError);
      expect(() => assertSafePath(repoRoot, '..\\..\\windows\\system32')).toThrow(ScannerSecurityError);
      expect(() => assertSafePath(repoRoot, '/etc/passwd')).toThrow(ScannerSecurityError);
    });

    test('assertSafePath rejects null bytes and protocol schemes', () => {
      const repoRoot = path.resolve('/var/app/repo');
      expect(() => assertSafePath(repoRoot, 'file\0.txt')).toThrow(ScannerSecurityError);
      expect(() => assertSafePath(repoRoot, 'http://malicious.site/payload')).toThrow(ScannerSecurityError);
    });

    test('assertSafeSymlink rejects symlinks pointing outside repository root', () => {
      const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'patchbay-sec-test-'));
      try {
        const repoRoot = path.join(tempDir, 'repo');
        const outsideDir = path.join(tempDir, 'outside');
        fs.mkdirSync(repoRoot);
        fs.mkdirSync(outsideDir);

        const outsideSecret = path.join(outsideDir, 'secret.txt');
        fs.writeFileSync(outsideSecret, 'super_secret_token');

        const symlinkPath = path.join(repoRoot, 'leaked_link');
        try {
          fs.symlinkSync(outsideSecret, symlinkPath, 'file');
          expect(() => assertSafeSymlink(repoRoot, symlinkPath)).toThrow(ScannerSecurityError);
        } catch (e) {
          // On some Windows environments, symlink creation requires admin rights
          if (e instanceof ScannerSecurityError) throw e;
        }
      } finally {
        fs.rmSync(tempDir, { recursive: true, force: true });
      }
    });

    test('ScanBudget enforces max file limit and max bytes limit', () => {
      const budget = new ScanBudget({ maxFiles: 3, maxTotalBytes: 1000 });

      expect(() => {
        budget.recordFile(200);
        budget.recordFile(200);
        budget.recordFile(200);
        budget.recordFile(200); // 4th file exceeds maxFiles 3
      }).toThrow(ScannerSecurityError);
    });
  });

