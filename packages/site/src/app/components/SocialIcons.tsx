export function SocialButtons({
  platforms = ['x', 'discord', 'linkedin', 'slack', 'youtube'],
  size = 18,
  className = '',
}: {
  platforms?: SocialPlatform[];
  size?: number;
  className?: string;
}) {
  const items = SOCIAL_LINKS.filter((item) => platforms.includes(item.name));

  return (
    <div className={`social-buttons-row ${className}`} role="list" aria-label="Social media links">
      {items.map((item) => (
        <a
          key={item.name}
          href={item.href}
          target="_blank"
          rel="noopener noreferrer"
          className="social-icon-btn"
          aria-label={item.label}
          title={item.label}
          role="listitem"
        >
          <SocialIcon name={item.name} size={size} />
        </a>
      ))}
    </div>
  );
}

